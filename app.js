// === Inicialización ===
function inicializarDatos() {
    // Si no existen datos o queremos sincronizar la base oficial
    const guardados = localStorage.getItem("miembrosMesaData");
    if (!guardados) {
        localStorage.setItem("miembrosMesaData", JSON.stringify(datosOficialesONPE));
        console.log("Datos oficiales ONPE guardados en LocalStorage.");
    } else {
        try {
            const parsed = JSON.parse(guardados);
            // Si el storage tiene datos incompletos o antiguos, asegurar que tenga los 27 oficiales
            if (parsed.length !== 27 || !parsed.some(m => m.dni === "47183573")) {
                localStorage.setItem("miembrosMesaData", JSON.stringify(datosOficialesONPE));
                console.log("Datos oficiales ONPE actualizados en LocalStorage.");
            }
        } catch (e) {
            localStorage.setItem("miembrosMesaData", JSON.stringify(datosOficialesONPE));
        }
    }
}

// === Exportar Copia de Seguridad JSON ===
function exportarDatosJSON() {
    const datos = obtenerDatos();
    const blob = new Blob([JSON.stringify(datos, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `miembros_onpe_${new Date().toISOString().slice(0, 10)}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

// === Obtener datos desde LocalStorage ===
function obtenerDatos() {
    const datos = localStorage.getItem("miembrosMesaData");
    return datos ? JSON.parse(datos) : [];
}

// === Controlador de Navegación SPA ===
function navegarA(vistaId, filtroMesa = null) {
    // Ocultar todas las secciones
    document.querySelectorAll('.vista-seccion').forEach(seccion => {
        seccion.classList.add('d-none');
    });

    // Desmarcar todos los enlaces de navegación
    document.querySelectorAll('.navbar-nav .nav-link').forEach(link => {
        link.classList.remove('active');
    });

    // Mostrar sección correspondiente
    const seccionDestino = document.getElementById(`vista-${vistaId}`);
    if (seccionDestino) {
        seccionDestino.classList.remove('d-none');
    }

    // Activar link en navbar
    const linkDestino = document.getElementById(`nav-${vistaId}`);
    if (linkDestino) {
        linkDestino.classList.add('active');
    }

    // Si se navega a miembros con filtro de mesa
    if (vistaId === 'miembros' && filtroMesa) {
        const selectMesa = document.getElementById('filtro-mesa');
        if (selectMesa) {
            selectMesa.value = filtroMesa;
            aplicarFiltros();
        }
    }

    // Cerrar navbar colapsable en pantallas móviles
    const navbarCollapse = document.getElementById('navbarContenido');
    if (navbarCollapse && navbarCollapse.classList.contains('show')) {
        const bsCollapse = bootstrap.Collapse.getInstance(navbarCollapse);
        if (bsCollapse) bsCollapse.hide();
    }

    window.scrollTo({ top: 0, behavior: 'smooth' });
}

// === Renderizar Dashboard ===
function renderizarDashboard(miembros) {
    const todos = miembros || obtenerDatos();
    const filtroMesa = document.getElementById("dashboard-filtro-mesa")?.value || "";
    const datosFiltrados = filtroMesa ? todos.filter(m => m.mesa === filtroMesa) : todos;

    const total = datosFiltrados.length;
    const contactados = datosFiltrados.filter(m => m.contactado).length;
    const credenciales = datosFiltrados.filter(m => m.credencial).length;
    const capacitados = datosFiltrados.filter(m => m.capacitacion).length;

    // Tarjetas principales
    document.getElementById("stat-total").textContent = total;
    document.getElementById("stat-contactados").textContent = contactados;
    document.getElementById("stat-credenciales").textContent = credenciales;
    document.getElementById("stat-capacitados").textContent = capacitados;

    // Resumen de pendientes
    const pendContacto = total - contactados;
    const pendCredencial = total - credenciales;
    const pendCapacitacion = total - capacitados;

    const elPendContacto = document.getElementById("stat-pendiente-contacto");
    const elPendCredencial = document.getElementById("stat-pendiente-credencial");
    const elPendCapacitacion = document.getElementById("stat-pendiente-capacitacion");

    if (elPendContacto) elPendContacto.textContent = pendContacto;
    if (elPendCredencial) elPendCredencial.textContent = pendCredencial;
    if (elPendCapacitacion) elPendCapacitacion.textContent = pendCapacitacion;

    // Avance general de gestión
    const tareasPosibles = total * 3;
    const tareasRealizadas = contactados + credenciales + capacitados;
    const porcentaje = tareasPosibles > 0 ? Math.round((tareasRealizadas / tareasPosibles) * 100) : 0;

    const barraProgreso = document.getElementById("stat-barra-progreso");
    const textoProgreso = document.getElementById("stat-porcentaje-progreso");
    if (barraProgreso) {
        barraProgreso.style.width = `${porcentaje}%`;
        barraProgreso.setAttribute("aria-valuenow", porcentaje);
    }
    if (textoProgreso) {
        textoProgreso.textContent = `${porcentaje}%`;
    }
}

