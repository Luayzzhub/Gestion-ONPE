// === Generar Enlace de WhatsApp ===
function generarEnlaceWhatsApp(miembro) {
    if (!miembro.telefono || miembro.telefono.trim() === "") return "#";

    let mensaje = "";

    if (!miembro.contactado) {
        mensaje = `Hola ${miembro.nombre || ''}, soy tu Coordinadora de la ONPE. Te escribo para coordinar tu participación como ${miembro.cargo} en la mesa ${miembro.mesa}.`;
    } else if (!miembro.credencial) {
        mensaje = `Hola ${miembro.nombre || ''}, te recuerdo que está pendiente la entrega de tu credencial de miembro de mesa.`;
    } else if (!miembro.capacitacion) {
        mensaje = `Hola ${miembro.nombre || ''}, te recuerdo que debes realizar tu capacitación de miembro de mesa lo antes posible.`;
    } else {
        mensaje = `Hola ${miembro.nombre || ''}, gracias por completar tus actividades previas. Nos vemos el día de las elecciones.`;
    }

    return `https://wa.me/51${miembro.telefono}?text=${encodeURIComponent(mensaje)}`;
}

