// === Abrir Modal de Gestión y Edición ===
function abrirModalGestion(id) {
    const miembros = obtenerDatos();
    const miembro = miembros.find(m => m.id === id);
    if (!miembro) return;

    // Asignación de mesa y cargo (informativo)
    document.getElementById("gestion-id").value = miembro.id;
    document.getElementById("gestion-mesa-badge").textContent = miembro.mesa;
    document.getElementById("gestion-cargo-badge").textContent = miembro.cargo;

    // Campos personales editables
    document.getElementById("gestion-nombre").value = miembro.nombre || "";
    document.getElementById("gestion-dni").value = miembro.dni || "";
    document.getElementById("gestion-telefono").value = miembro.telefono || "";
    document.getElementById("gestion-direccion").value = miembro.direccion || "";
    document.getElementById("check-vive-direccion").checked = Boolean(miembro.viveEnDireccion);

    // Checkboxes de actividades ONPE
    document.getElementById("check-contactado").checked = Boolean(miembro.contactado);
    document.getElementById("check-credencial").checked = Boolean(miembro.credencial);
    document.getElementById("check-capacitacion").checked = Boolean(miembro.capacitacion);

    // Observaciones
    document.getElementById("text-observaciones").value = miembro.observaciones || "";

    // Mostrar modal
    const modal = new bootstrap.Modal(document.getElementById("modalGestion"));
    modal.show();
}

// === Aplicar Filtros ===
function aplicarFiltros() {
    const todos = obtenerDatos();
    const busqueda = document.getElementById("input-busqueda").value.toLowerCase();
    const mesa = document.getElementById("filtro-mesa").value;
    const cargo = document.getElementById("filtro-cargo").value;
    const estado = document.getElementById("filtro-estado").value;

    const filtrados = todos.filter(m => {
        // Búsqueda por DNI, Nombre o Dirección
        const coincideBusqueda = !busqueda ||
            (m.dni && m.dni.toLowerCase().includes(busqueda)) ||
            (m.nombre && m.nombre.toLowerCase().includes(busqueda)) ||
            (m.direccion && m.direccion.toLowerCase().includes(busqueda));

        // Filtro por Mesa
        const coincideMesa = !mesa || m.mesa === mesa;

        // Filtro por Cargo
        const coincideCargo = !cargo || m.cargo === cargo;

        // Filtro por Estado
        let coincideEstado = true;
        // Estados cumplidos
        if (estado === "es-contactado") coincideEstado = Boolean(m.contactado);
        else if (estado === "es-credencial") coincideEstado = Boolean(m.credencial);
        else if (estado === "es-capacitacion") coincideEstado = Boolean(m.capacitacion);
        else if (estado === "completado-todo") coincideEstado = Boolean(m.contactado && m.credencial && m.capacitacion);
        else if (estado === "vive-aqui") coincideEstado = Boolean(m.direccion && m.viveEnDireccion);
        // Estados pendientes
        else if (estado === "falta-contacto") coincideEstado = !m.contactado;
        else if (estado === "falta-credencial") coincideEstado = !m.credencial;
        else if (estado === "falta-capacitacion") coincideEstado = !m.capacitacion;
        else if (estado === "no-vive") coincideEstado = Boolean(m.direccion && !m.viveEnDireccion);

        return coincideBusqueda && coincideMesa && coincideCargo && coincideEstado;
    });

    renderizarMiembros(filtrados);
}

// === Arranque ===
document.addEventListener("DOMContentLoaded", () => {
    inicializarDatos();
    const miembros = obtenerDatos();
    renderizarDashboard(miembros);
    renderizarMesas(miembros);
    renderizarMiembros(miembros);

    // Listener del filtro de mesa en el Dashboard
    const filtroMesaDashboard = document.getElementById("dashboard-filtro-mesa");
    if (filtroMesaDashboard) {
        filtroMesaDashboard.addEventListener("change", () => {
            renderizarDashboard();
        });
    }

    // Listeners de filtros en Gestión de Miembros
    document.getElementById("input-busqueda").addEventListener("input", aplicarFiltros);
    document.getElementById("filtro-mesa").addEventListener("change", aplicarFiltros);
    document.getElementById("filtro-cargo").addEventListener("change", aplicarFiltros);
    document.getElementById("filtro-estado").addEventListener("change", aplicarFiltros);

    // Botón limpiar filtros
    document.getElementById("btn-limpiar").addEventListener("click", () => {
        document.getElementById("input-busqueda").value = "";
        document.getElementById("filtro-mesa").value = "";
        document.getElementById("filtro-cargo").value = "";
        document.getElementById("filtro-estado").value = "";
        aplicarFiltros();
    });

    // Listener del formulario de gestión y edición
    document.getElementById("form-gestion").addEventListener("submit", (e) => {
        e.preventDefault();

        const id = document.getElementById("gestion-id").value;
        const nombre = document.getElementById("gestion-nombre").value.trim();
        const dni = document.getElementById("gestion-dni").value.trim();
        const telefono = document.getElementById("gestion-telefono").value.trim();
        const direccion = document.getElementById("gestion-direccion").value.trim();
        const viveEnDireccion = document.getElementById("check-vive-direccion").checked;

        const contactado = document.getElementById("check-contactado").checked;
        const credencial = document.getElementById("check-credencial").checked;
        const capacitacion = document.getElementById("check-capacitacion").checked;
        const observaciones = document.getElementById("text-observaciones").value.trim();

        // Actualizar datos en LocalStorage
        const miembros = obtenerDatos();
        const miembro = miembros.find(m => m.id === id);
        if (miembro) {
            miembro.nombre = nombre;
            miembro.dni = dni;
            miembro.telefono = telefono;
            miembro.direccion = direccion;
            miembro.viveEnDireccion = viveEnDireccion;
            miembro.contactado = contactado;
            miembro.credencial = credencial;
            miembro.capacitacion = capacitacion;
            miembro.observaciones = observaciones;
            localStorage.setItem("miembrosMesaData", JSON.stringify(miembros));
        }

        // Cerrar modal
        const modalEl = document.getElementById("modalGestion");
        const modalInstance = bootstrap.Modal.getInstance(modalEl);
        if (modalInstance) modalInstance.hide();

        // Refrescar interfaz en todas las vistas respetando filtros activos
        const datosActualizados = obtenerDatos();
        renderizarDashboard(datosActualizados);
        renderizarMesas(datosActualizados);
        aplicarFiltros();
    });
});

// === Atajo de teclado: Ctrl + Shift + R para resetear datos ===
document.addEventListener("keydown", (e) => {
    if (e.ctrlKey && e.shiftKey && e.key === "R") {
        e.preventDefault();
        localStorage.removeItem("miembrosMesaData");
        location.reload();
    }
});
